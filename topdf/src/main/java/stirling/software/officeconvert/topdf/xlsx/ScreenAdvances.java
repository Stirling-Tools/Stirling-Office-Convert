    private ScreenAdvances() {}

    private static void row(String family, int style, int ppem, String advances) {
        ROWS.put(key(family, style, ppem), advances);
    }

    private static String key(String family, int style, int ppem) {
        return family.toLowerCase(Locale.ROOT) + '/' + style + '/' + ppem;
    }

    static boolean emulates(String family, FontFace face) {
        String f = family == null ? null : family.trim();
        return (CALIBRI.equalsIgnoreCase(f) || ARIAL.equalsIgnoreCase(f)) && face != null
                && !face.family().equalsIgnoreCase(f);
    }

    static int advance(String family, boolean bold, boolean italic, int codePoint, int ppem) {
        return advance(row(family, bold, italic, ppem), codePoint);
    }

    static String row(String family, boolean bold, boolean italic, int ppem) {
        return family == null ? null : ROWS.get(key(family.trim(), (bold ? 1 : 0) + (italic ? 2 : 0), ppem));
    }

    static int advance(String row, int codePoint) {
        int i = index(codePoint);
        if (row == null || i < 0) {
            return -1;
        }
        char c = row.charAt(i);
        return c == '~' ? -1 : c - '0';
    }

    private static int index(int cp) {
        if (cp >= 32 && cp < 127) {
            return cp - 32;
        }
        if (cp >= 160 && cp < 256) {
            return 95 + cp - 160;
        }
        for (int i = 0; i < EXTRA.length; i++) {
            if (EXTRA[i] == cp) {
                return 191 + i;
            }
        }
        return -1;
    }
