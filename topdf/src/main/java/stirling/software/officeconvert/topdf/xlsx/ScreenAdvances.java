    private ScreenAdvances() {}

    private static void row(int style, int ppem, String advances) {
        CALIBRI_ROWS.put(style << 8 | ppem, advances);
    }

    static boolean emulates(String family, FontFace face) {
        return family != null && family.trim().equalsIgnoreCase(CALIBRI) && face != null
                && !face.family().equalsIgnoreCase(CALIBRI);
    }

    static int calibri(boolean bold, boolean italic, int codePoint, int ppem) {
        String row = CALIBRI_ROWS.get((bold ? 1 : 0) + (italic ? 2 : 0) << 8 | ppem);
        int i = index(codePoint);
        if (row == null || i < 0) {
            return -1;
        }
        char c = row.charAt(i);
        return c == '~' ? -1 : c - '0';
    }

    private static int index(int cp) {
        if (cp >= 32 && cp < 127) {
            return cp - 32;
        }
        if (cp >= 160 && cp < 256) {
            return 95 + cp - 160;
        }
        for (int i = 0; i < EXTRA.length; i++) {
            if (EXTRA[i] == cp) {
                return 191 + i;
            }
        }
        return -1;
    }
