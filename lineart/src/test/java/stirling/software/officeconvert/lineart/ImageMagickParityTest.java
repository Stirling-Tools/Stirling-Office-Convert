    @ParameterizedTest
    @ValueSource(ints = {1, 2, 3})
    void edgesMatchImageMagickPixelForPixel(int level) {
        assertMatches(LineArt.binarize(picture(), LineArt.Options.imageMagickEdges(level)), EXPECTED[level - 1]);
    }

    @ParameterizedTest
    @ValueSource(ints = {1, 2, 3})
    void edgesIgnoreThresholdLikeImageMagickBilevelType(int level) {
        for (double threshold : new double[] {20, 55, 70}) {
            assertMatches(LineArt.binarize(picture(), LineArt.Options.imageMagickEdges(level).threshold(threshold)),
                    EXPECTED[level - 1]);
        }
    }

    private static void assertMatches(Bitmap bitmap, String[] expected) {
        StringBuilder actual = new StringBuilder();
        StringBuilder wanted = new StringBuilder();
        for (int y = 0; y < 32; y++) {
            for (int x = 0; x < 48; x++) {
                actual.append(bitmap.ink(x, y) ? '#' : '.');
            }
            actual.append('\n');
            wanted.append(expected[y]).append('\n');
        }
        assertEquals(wanted.toString(), actual.toString());
    }

    private static BufferedImage picture() {
        BufferedImage image = new BufferedImage(48, 32, BufferedImage.TYPE_INT_RGB);
        for (int y = 0; y < 32; y++) {
            for (int x = 0; x < 48; x++) {
                image.setRGB(x, y, pixel(x, y));
            }
        }
        return image;
    }

    private static int pixel(int x, int y) {
        int r = 255 - x * 3;
        int g = 255 - x * 3;
        int b = 255 - x * 2;
        if (x >= 6 && x < 20 && y >= 8 && y < 22) {
            r = 10;
            g = 10;
            b = 10;
        }
        double d = Math.hypot(x - 34, y - 16);
        if (d < 9) {
            r = 200;
            g = 40;
            b = 40;
        } else if (d < 10.5) {
            double t = (d - 9) / 1.5;
            r = (int) (200 * (1 - t) + r * t);
            g = (int) (40 * (1 - t) + g * t);
            b = (int) (40 * (1 - t) + b * t);
        }
        if (Math.abs(y - x / 2.0) < 1) {
            r = 40;
            g = 40;
            b = 200;
        }
        int n = (x * 7919 + y * 104729) % 23 - 11;
        r = Math.clamp(r + n, 0, 255);
        g = Math.clamp(g + n, 0, 255);
        b = Math.clamp(b + n, 0, 255);
        return r << 16 | g << 8 | b;
    }
